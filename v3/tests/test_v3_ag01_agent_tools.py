"""AG01 / EN06 / AG02: pipeline steps as Snowflake procedures, and a Cortex Agent over them. Written before the code.
Design (owner decision 21 Nov: "make the design call"):
  * Three procedures in WBR_DB.V3_AGENT, all READ-ONLY on workbook data, EXECUTE AS CALLER (a user only reaches what
    their own role can read): V3_ASSESS(stage_path) parses one workbook from a stage and returns a compact summary;
    V3_ASSESS_BATCH(stage_paths) does it for a comma-separated list (EN06), one failure never stops the others;
    V3_RUN_STATUS(run_id) returns a stored summary. Each run is recorded in WBR_DB.V3_AGENT.RUNS (bound values).
    Procedures return one VARIANT under the agent's 32 KB tool limit (summaries are capped).
  * No procedure deploys, loads data, applies a fix or calls Cortex: deploy stays a person's button in the console.
  * The setup SQL is generated by code and run by the owner (never OR REPLACE); the procedures import the release's
    candidate.zip from a stage the owner names.
  * AG02: the agent spec lists the three procedures as custom tools (type generic, resource type procedure) and
    instructs the agent that it can only assess and report; verdicts come from the summaries, never from the agent.
  * Summaries carry no file paths, credentials or data values: datasource bindings are reported as states."""
from pathlib import Path
import json
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import v3_agent_tools as AT  # noqa: E402

RESULT = {
    'ir': {'workbook_name': 'Book', 'dashboards': [{'name': 'D1', 'sheets': [{'name': 'S1'}, {'name': 'S2'}]}]},
    'assessment': {'state': 'PARTIAL', 'issues': [{'severity': 'warning'}],
                   'sheets': [{'dashboard': 'D1', 'sheet': 'S1', 'kind': 'bar', 'state': 'SUPPORTED', 'reason': ''},
                              {'dashboard': 'D1', 'sheet': 'S2', 'kind': 'planned', 'state': 'PARTIAL',
                               'reason': 'Exact plan; not yet verified'}],
                   'untranslated_calculations': ['Calc A', 'Calc B']},
    'bindings': {'Orders': 'DB.S.ORDERS', 'Targets': '/tmp/tableau-v3-x/Targets.xlsx', 'Returns': None},
}


class Session:
    def __init__(self, rows=None, fail=False):
        self.sqls, self.params, self.rows, self.fail = [], [], rows or [], fail

    def sql(self, text, params=None):
        self.sqls.append(text)
        self.params.append(params)
        outer = self

        class Q:
            def collect(self):
                if outer.fail:
                    raise RuntimeError('no table')
                return outer.rows
        return Q()


class Summary(unittest.TestCase):
    def test_compact_and_without_paths(self):
        s = AT.summarize(RESULT, 'Book.twbx')
        self.assertEqual(s['sheets'], {'total': 2, 'SUPPORTED': 1, 'PARTIAL': 1})
        self.assertEqual(s['untranslated_calculations'], ['Calc A', 'Calc B'])
        self.assertEqual(s['datasources'], {'Orders': 'bound to a Snowflake table', 'Targets': 'file in the workbook',
                                            'Returns': 'not bound'})
        self.assertNotIn('/tmp', json.dumps(s))
        self.assertNotIn('DB.S.ORDERS', json.dumps(s))

    def test_capped_under_the_tool_limit(self):
        big = json.loads(json.dumps(RESULT))
        big['assessment']['untranslated_calculations'] = [f'Calc {i} ' + 'x' * 200 for i in range(2000)]
        big['assessment']['sheets'] = [dict(RESULT['assessment']['sheets'][1], sheet=f'S{i}') for i in range(3000)]
        self.assertLess(len(json.dumps(AT.summarize(big, 'Big.twbx'))), AT.MAX_BYTES)


class Procedures(unittest.TestCase):
    def test_stage_path_is_validated(self):
        for bad in ("@DB.S.ST/a.twbx'; DROP TABLE X", 'DB.S.ST/a.twbx', '@DB.S.ST/../x.twbx', '@DB.S.ST/a.exe', ''):
            self.assertFalse(AT.stage_path_ok(bad), bad)
        self.assertTrue(AT.stage_path_ok('@WBR_DB.V3_AGENT.WORKBOOKS/sales/Sales Dashboard.twbx'))

    def test_assess_records_the_run_with_bound_values(self):
        s = Session()
        out = AT.assess(s, '@WBR_DB.V3_AGENT.WORKBOOKS/Book.twbx', reader=lambda sess, p: b'raw',
                        intake=lambda raw, name: RESULT)
        self.assertEqual(out['status'], 'OK')
        self.assertTrue(out['run_id'])
        ins = [q for q in s.sqls if q.lstrip().upper().startswith('INSERT')]
        self.assertEqual(len(ins), 1)
        self.assertIn('WBR_DB.V3_AGENT.RUNS', ins[0])
        self.assertNotIn('Book', ins[0])                               # values bound
        self.assertFalse(any(k in ' '.join(s.sqls).upper() for k in ('CREATE ', 'DROP ', 'MERGE ', 'GRANT ')))

    def test_assess_failures_are_codes(self):
        out = AT.assess(Session(), '@WBR_DB.V3_AGENT.WORKBOOKS/Book.twbx',
                        reader=lambda sess, p: (_ for _ in ()).throw(RuntimeError('secret detail')),
                        intake=lambda raw, name: RESULT)
        self.assertEqual(out['status'], 'READ_FAILED:RuntimeError')
        self.assertNotIn('secret detail', json.dumps(out))
        self.assertEqual(AT.assess(Session(), 'bad path')['status'], 'STAGE_PATH_REFUSED')

    def test_batch_continues_after_a_failure(self):
        calls = []

        def intake(raw, name):
            calls.append(name)
            if name == 'Bad.twbx':
                raise ValueError('broken')
            return RESULT
        out = AT.assess_batch(Session(), '@WBR_DB.V3_AGENT.WORKBOOKS/A.twbx, @WBR_DB.V3_AGENT.WORKBOOKS/Bad.twbx,'
                                         '@WBR_DB.V3_AGENT.WORKBOOKS/C.twbx',
                              reader=lambda sess, p: b'raw', intake=intake)
        self.assertEqual([r['status'] for r in out['runs']], ['OK', 'INTAKE_FAILED:ValueError', 'OK'])
        self.assertEqual(out['escalated'], ['Bad.twbx'])
        self.assertEqual(calls, ['A.twbx', 'Bad.twbx', 'C.twbx'])
        self.assertLess(len(json.dumps(out)), AT.MAX_BYTES)

    def test_status_reads_a_stored_summary(self):
        s = Session(rows=[(json.dumps({'workbook': 'Book.twbx', 'state': 'PARTIAL'}),)])
        out = AT.run_status(s, 'a1b2c3d4-0000-0000-0000-000000000000')
        self.assertEqual(out['summary']['state'], 'PARTIAL')
        self.assertEqual(s.params[0], ['a1b2c3d4-0000-0000-0000-000000000000'])
        self.assertEqual(AT.run_status(s, "x' OR 1=1")['status'], 'RUN_ID_REFUSED')

    def test_no_procedure_deploys_loads_or_calls_cortex(self):
        src = (ROOT / 'v3_agent_tools.py').read_text(encoding='utf-8')
        for word in ('v3_deploy', 'deploy_streamlit_app', 'AI_COMPLETE', 'v3_data_load', 'apply_verified', 'write_pandas'):
            self.assertNotIn(word, src)


class SetupSql(unittest.TestCase):
    def test_procedures_are_caller_rights_and_never_replaced(self):
        sql = '\n'.join(AT.setup_sql('@WBR_DB.V3_AGENT.RELEASES/candidate.zip', 'POWERHOUSE', 'WBR_OWNER'))
        self.assertNotIn('OR REPLACE', sql)
        for p in ('V3_ASSESS(', 'V3_ASSESS_BATCH(', 'V3_RUN_STATUS('):
            self.assertIn('CREATE PROCEDURE IF NOT EXISTS WBR_DB.V3_AGENT.' + p, sql)
        self.assertEqual(sql.count('EXECUTE AS CALLER'), 3)
        self.assertIn("IMPORTS = ('@WBR_DB.V3_AGENT.RELEASES/candidate.zip')", sql)
        self.assertIn('CREATE TABLE IF NOT EXISTS WBR_DB.V3_AGENT.RUNS', sql)
        self.assertIn('RETURNS VARIANT', sql)
        with self.assertRaises(ValueError):
            AT.setup_sql("@X.Y.Z/a.zip'); DROP", 'POWERHOUSE', 'WBR_OWNER')


class AgentSpec(unittest.TestCase):
    def test_tools_are_the_three_procedures_and_nothing_deploys(self):
        spec = AT.agent_spec('POWERHOUSE')
        names = [t['tool_spec']['name'] for t in spec['tools']]
        self.assertEqual(names, ['v3_assess', 'v3_assess_batch', 'v3_run_status'])
        self.assertTrue(all(t['tool_spec']['type'] == 'generic' for t in spec['tools']))
        for n in names:
            res = spec['tool_resources'][n]
            self.assertEqual(res['type'], 'procedure')
            self.assertTrue(res['identifier'].startswith('WBR_DB.V3_AGENT.V3_'))
            self.assertEqual(res['execution_environment']['warehouse'], 'POWERHOUSE')
        text = json.dumps(spec['instructions']).lower()
        self.assertIn('never deploy', text)
        self.assertEqual(spec['orchestration']['tool_not_accessible'], 'reject')

    def test_agent_setup_sql(self):
        sql = '\n'.join(AT.agent_setup_sql('POWERHOUSE', 'WBR_OWNER'))
        self.assertIn('CREATE AGENT IF NOT EXISTS WBR_DB.V3_AGENT.V3_MIGRATION_AGENT', sql)
        self.assertIn('GRANT USAGE ON AGENT WBR_DB.V3_AGENT.V3_MIGRATION_AGENT TO ROLE WBR_OWNER', sql)
        self.assertNotIn('OR REPLACE', sql)

    def test_console_shows_the_setup(self):
        self.assertIn('v3_agent_tools', (ROOT / 'v3_console.py').read_text(encoding='utf-8'))


if __name__ == '__main__':
    unittest.main()
