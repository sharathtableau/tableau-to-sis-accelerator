"""AG03 Ask the data through a Cortex Agent, and CF03 evaluation against verified queries. Written before the code.
AG03 (Snowflake recommends agents over direct Cortex Analyst calls):
  * One ask agent per Semantic View (WBR_DB.CX_AGENTS.V3_ASK_<hash>), Cortex Analyst on the view as its only tool;
    setup SQL generated by code, run by the owner. When it exists, Ask the data goes through it
    (SNOWFLAKE.CORTEX.DATA_AGENT_RUN); otherwise, or on any agent failure, the direct Cortex Analyst call as before.
  * Either way the SQL is shown and run by the app only as one read-only query with a row limit; the route is shown.
  * Errors reach the screen as codes only (no Cortex / Snowflake error text).
CF03 (owner decision 21 Nov: the evaluation may run Cortex Analyst's own SQL, read-only):
  * Every verified query of the run (CF02) is asked as its question; Cortex Analyst's SQL runs read-only; its numbers
    are compared with the code-built SEMANTIC_VIEW() proof query (already equal to Tableau). sql_correctness = the
    share of questions whose every metric column is matched (same row count, values within 1e-6 relative).
  * The scorecard (CF01) counts it."""
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import v3_ask as AK  # noqa: E402
import v3_analyst_eval as EV  # noqa: E402

VIEW = 'WBR_DB.PUBLIC.SALES_SEMANTIC'


class Row(dict):
    def as_dict(self):
        return dict(self)


class Sess:
    def __init__(self, results):
        self.results, self.sqls = results, []

    def sql(self, q, params=None):
        self.sqls.append(q)
        outer = self

        class R:
            def collect(self):
                for key, rows in outer.results.items():
                    if key in q:
                        return [r if isinstance(r, Row) else Row(r) for r in rows] if isinstance(rows, list) else rows
                return []
        return R()


class AskAgent(unittest.TestCase):
    def test_agent_name_and_setup_sql(self):
        name = AK.ask_agent_name(VIEW)
        self.assertRegex(name, r'^WBR_DB\.CX_AGENTS\.V3_ASK_[0-9A-F]{10}$')
        self.assertEqual(name, AK.ask_agent_name(VIEW))
        sql = '\n'.join(AK.ask_agent_setup_sql(VIEW, 'POWERHOUSE', 'WBR_OWNER'))
        self.assertIn('CREATE AGENT IF NOT EXISTS ' + name, sql)
        self.assertIn('cortex_analyst_text_to_sql', sql)
        self.assertIn(VIEW, sql)
        self.assertNotIn('OR REPLACE', sql)

    def test_routes_through_the_agent_when_it_exists(self):
        calls = []
        reply = {'content': [{'type': 'text', 'text': 'Revenue by region'},
                             {'type': 'tool_result', 'content': [{'json': {'sql': 'SELECT REGION, SUM(SALES) AS S FROM T GROUP BY 1'}}]}]}
        s = Sess({'SELECT * FROM (SELECT REGION': [{'REGION': 'East', 'S': 1.0}]})
        out = AK._answer(s, VIEW, 'revenue by region', agent=lambda sess, name, q: calls.append(name) or reply,
                         analyst=lambda v, q: (_ for _ in ()).throw(AssertionError('analyst must not be called')))
        self.assertEqual(out['route'], 'Cortex Agent')
        self.assertEqual(out['rows'], [{'REGION': 'East', 'S': 1.0}])
        self.assertTrue(calls)

    def test_falls_back_to_analyst_and_codes_only(self):
        s = Sess({'SELECT * FROM (SELECT 1': [{'X': 1}]})
        out = AK._answer(s, VIEW, 'q', agent=lambda sess, name, q: None,
                         analyst=lambda v, q: ('SELECT 1 AS X', 'one'))
        self.assertEqual(out['route'], 'Cortex Analyst')
        out = AK._answer(s, VIEW, 'q', agent=lambda sess, name, q: None,
                         analyst=lambda v, q: (_ for _ in ()).throw(RuntimeError('HTTP 400: internal detail')))
        self.assertTrue(out['error'].startswith('ANALYST_FAILED'))
        self.assertNotIn('internal detail', str(out))
        out = AK._answer(s, VIEW, 'q', agent=lambda sess, name, q: None,
                         analyst=lambda v, q: ('DELETE FROM T', ''))
        self.assertEqual(out['error'], 'SQL_REFUSED:ValueError')
        self.assertIsNone(out['rows'])

    def test_render_shows_no_exception_text(self):
        src = (ROOT / 'v3_ask.py').read_text(encoding='utf-8')
        self.assertNotIn("str(exc)[:300]", src)


VQ = {'sheet': 'Sales by Region', 'state': 'VERIFIED', 'question': 'What is the total Sales by Region?',
      'proof_sql': 'SELECT * FROM SEMANTIC_VIEW(WBR_DB.PUBLIC.SALES_SEMANTIC DIMENSIONS ORDERS.REGION '
                   'METRICS ORDERS.TOTAL_SALES)', 'dims': ['REGION'],
      'measures': [{'metric': 'TOTAL_SALES', 'caption': 'Sales'}], 'datasource': 'Sales'}


class Evaluation(unittest.TestCase):
    def proof(self):
        return [Row(REGION='East', TOTAL_SALES=10.0), Row(REGION='West', TOTAL_SALES=20.0)]

    def test_matching_answer_is_correct(self):
        s = Sess({'SEMANTIC_VIEW(': self.proof(),
                  'SELECT * FROM (SELECT R': [{'R': 'West', 'TOT': 20.0000000001}, {'R': 'East', 'TOT': 10.0}]})
        out = EV.evaluate(s, VIEW, [VQ], ask=lambda v, q: ('SELECT R, TOT FROM X', ''))
        self.assertEqual(out['rows'][0]['Result'], 'Correct')
        self.assertEqual(out['sql_correctness'], 1.0)

    def test_wrong_values_rows_or_refused_sql(self):
        cases = [([{'R': 'East', 'TOT': 10.0}, {'R': 'West', 'TOT': 25.0}], 'SELECT R, TOT FROM X', 'Incorrect'),
                 ([{'R': 'East', 'TOT': 10.0}], 'SELECT R, TOT FROM X', 'Incorrect'),
                 ([], 'DROP TABLE X', 'SQL refused')]
        for rows, sql, want in cases:
            s = Sess({'SEMANTIC_VIEW(': self.proof(), 'SELECT * FROM (SELECT R': rows})
            out = EV.evaluate(s, VIEW, [VQ], ask=lambda v, q, sql=sql: (sql, ''))
            self.assertEqual(out['rows'][0]['Result'], want, sql)
            self.assertEqual(out['sql_correctness'], 0.0)

    def test_only_verified_queries_and_codes(self):
        out = EV.evaluate(Sess({}), VIEW, [dict(VQ, state='NOT_MATCHED')], ask=lambda v, q: ('SELECT 1', ''))
        self.assertEqual(out['rows'], [])
        out = EV.evaluate(Sess({'SEMANTIC_VIEW(': self.proof()}), VIEW, [VQ],
                          ask=lambda v, q: (_ for _ in ()).throw(RuntimeError('detail')))
        self.assertEqual(out['rows'][0]['Result'], 'ANALYST_FAILED:RuntimeError')

    def test_scorecard_counts_it(self):
        import v3_scorecard as SC
        rows = SC.scorecard({'cf03': {'rows': [{'Result': 'Correct'}, {'Result': 'Incorrect'},
                                               {'Result': 'ANALYST_FAILED:X'}]}})
        r = next(x for x in rows if x['Decision'].startswith('Ask the data'))
        self.assertEqual((r['Cortex proposed'], r['Passed code check'], r['Rejected by code']), (2, 1, 1))

    def test_console_offers_it(self):
        self.assertIn('v3_analyst_eval', (ROOT / 'v3_console.py').read_text(encoding='utf-8'))


