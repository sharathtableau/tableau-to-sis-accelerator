"""Snowflake Semantic View generated from a verified Tableau relationship model.

For a Tableau datasource built from relationships (or joins) the V3 engine already holds a
typed, verified plan: the logical tables, the authored relationship keys and the fact table
(v3_model_binding.build / validate). This module turns that plan into a Snowflake Semantic
View and lets the dashboard read its data through it:

  TABLES         one per Tableau logical table; dimension tables get their verified key
                 as PRIMARY KEY (validate() proved it non-null and unique)
  RELATIONSHIPS  exactly the authored relationship keys (fact -> dimension)
  DIMENSIONS     every field (names = the model's column names); numeric ones are
                 aggregated through METRICS
  METRICS        SUM of every numeric fact, COUNT DISTINCT of every relationship key, plus
                 each Tableau calculation that is self-contained (no parameters, no table
                 sub-queries, no window functions) - verified by executing it; others are listed
                 as not included, never rewritten

relation_sql() is the row-level relation the dashboard queries once the view exists:
SEMANTIC_VIEW(<view> DIMENSIONS ... FACTS ...). It is attached only after verify() proves it
returns the same rows (count) and the same totals for every numeric column as the authored
relationship model; otherwise the dashboard keeps the verified model query.
Names come from the plan; nothing is generated by a model. Creating the view is a Snowflake
write and only happens from an explicit button.
"""
import hashlib
import json
import re

from v3_model_binding import compile_query, quote

DB, SCHEMA = 'WBR_DB', 'TABLEAU_ACCELERATOR_V3'
NUMERIC = {'integer', 'real'}
_BARE = re.compile(r'[A-Z_][A-Z0-9_]*\Z')
_UNSAFE = re.compile(r'__PARAM_|__TBL__|\bSELECT\b|\bOVER\s*\(|;', re.I)


# Cortex lab copy: its Semantic Views carry a LAB tag so they never replace the stable build's views.
LAB = 'LAB'

def _ident(name):
    return name if _BARE.fullmatch(name) else quote(name)


def _alias(caption, used):
    base = re.sub(r'[^a-z0-9]+', '_', (caption or 't').lower()).strip('_') or 't'
    if base[0].isdigit():
        base = 't_' + base
    alias, n = base, 2
    while alias in used:
        alias, n = f'{base}_{n}', n + 1
    used.add(alias)
    return alias


def _lit(text):
    return "'" + str(text).replace("'", "''") + "'"


def _syn(entry):
    names = []
    for n in [entry['caption']] + list(entry.get('synonyms') or []):
        if n and n.lower() not in [x.lower() for x in names]:
            names.append(n)
    return ', '.join(_lit(n) for n in names)


SEMANTIC_KEYS = ('semantic_view', 'semantic_mode', 'semantic_label', 'semantic_map')


def base_plan(plan):
    """The relationship plan without the attached-view markers."""
    return {k: v for k, v in plan.items() if k not in SEMANTIC_KEYS}


def exact_part(plan):
    """DM8: (the plan without its one-row-per-key tables and the tables reached through them, [left-out tables]).
    A Semantic View declares physical tables with a primary key, so a table read as SELECT DISTINCT cannot be in
    it; the dashboard keeps reading the whole model through the verified query."""
    out = base_plan(plan)
    drop = {oid for oid, t in out['tables'].items() if t.get('distinct')}
    grew = True
    while grew:
        grew = False
        for k in out['keys']:
            if k['first'] in drop and k['second'] not in drop:
                drop.add(k['second'])
                grew = True
    left_out = [dict(out['tables'][oid], id=oid) for oid in sorted(drop)]
    out = dict(out, tables={oid: t for oid, t in out['tables'].items() if oid not in drop},
               fields={n: f for n, f in out['fields'].items() if f['owner'] not in drop},
               keys=[k for k in out['keys'] if k['second'] not in drop])
    return out, left_out


def label(caption):
    """Readable name part from the Tableau datasource caption, e.g. ECOMMERCE_DATASET_LIVE_SNOWFLAKE_JOIN."""
    slug = re.sub(r'[^A-Z0-9]+', '_', re.sub(r"[-'’]", '', str(caption or '').upper())).strip('_')[:48].strip('_')
    if slug and slug[0].isdigit():
        slug = 'DS_' + slug
    return slug or None


def view_name(plan, caption=None):
    """<DATASOURCE CAPTION>_SV_<plan hash>: readable, and still unique to the exact relationship plan."""
    core = {k: plan[k] for k in ('root', 'tables', 'keys', 'fields')}
    digest = hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest()[:8].upper()
    slug = plan.get('semantic_label') or label(caption)
    return f'{DB}.{SCHEMA}.{slug}_SV{LAB}_{digest}' if slug else f'{DB}.{SCHEMA}.V3_SV{LAB}_{digest}'


def key_cols(x):
    """E04: a relationship / primary key is one column or, for a composite key, a list of columns."""
    return list(x) if isinstance(x, (list, tuple)) else [x]


def plan_key(k, side):
    """The key of one plan relationship on 'left' or 'right': a column, or a list of columns (composite)."""
    pairs = k.get('pairs')
    if not pairs:
        return k[side]
    return [p[0 if side == 'left' else 1] for p in pairs]


def model(plan, ir=None, caption=None):
    """Structured semantic model (tables, relationships, facts, dimensions, metrics, skipped)."""
    compile_query(plan)  # same validation as the dashboard query
    used, aliases = set(), {}
    for oid in [plan['root']] + sorted(o for o in plan['tables'] if o != plan['root']):
        aliases[oid] = _alias(plan['tables'][oid]['caption'], used)
    dim_keys = {}
    for k in plan['keys']:
        dim_keys.setdefault(k['second'], plan_key(k, 'right'))
    tables = [{'alias': aliases[oid], 'table': t['table'], 'caption': t['caption'],
               'role': 'fact' if oid == plan['root'] else 'dimension',
               'primary_key': dim_keys.get(oid)} for oid, t in plan['tables'].items()]
    relationships = [{'name': f"{aliases[k['first']]}_to_{aliases[k['second']]}",
                      'from': aliases[k['first']], 'from_key': plan_key(k, 'left'), 'to': aliases[k['second']],
                      'to_key': plan_key(k, 'right')} for k in plan['keys']]
    facts, dims = [], []
    for local, f in sorted(plan['fields'].items(), key=lambda kv: kv[1]['output']):
        entry = {'table': aliases[f['owner']], 'name': f['output'], 'column': f['remote'],
                 'caption': re.sub(r'[_\s]+', ' ', local).strip().title(), 'datatype': f['datatype']}
        # Every column is a DIMENSION (Snowflake: a query mixing FACTS with dimensions must stay
        # inside one logical table; dimensions can be read row-level across the related tables).
        # Numeric columns stay aggregatable through the METRICS below.
        entry['numeric'] = f['datatype'] in NUMERIC
        dims.append(entry)
    metrics, names = [], {e['name'] for e in facts + dims}
    for f in [d for d in dims if d.get('numeric')]:
        if f['table'] != aliases[plan['root']] or re.search(r'LATITUDE|LONGITUDE|_RATE', f['name']):
            continue                  # additive totals only for fact-table measures
        name = 'TOTAL_' + f['name']
        if name not in names:
            names.add(name)
            metrics.append({'table': f['table'], 'name': name, 'expr': f"SUM({f['table']}.{f['name']})",
                            'caption': 'Total ' + f['caption'], 'source': 'generated'})
    for r in relationships:
        if isinstance(r['from_key'], list):
            continue                  # a composite key has no single distinct-count metric
        name = 'DISTINCT_' + r['from_key']
        if name not in names:
            names.add(name)
            key = next((d for d in dims + facts if d['table'] == r['from'] and d['column'] == r['from_key']), None)
            if key is None:
                continue
            metrics.append({'table': r['from'], 'name': name, 'expr': f"COUNT(DISTINCT {r['from']}.{key['name']})",
                            'caption': 'Distinct ' + r['from_key'].lower().replace('_', ' '), 'source': 'generated'})
    skipped = []
    if ir is not None:
        root_alias = aliases[plan['root']]
        columns = {e['column']: f"{e['table']}.{e['name']}" for e in facts + dims if e['table'] == root_alias}
        skipped = _calc_metrics(ir, columns, root_alias, names, metrics)
    return {'name': view_name(plan, caption), 'caption': caption, 'tables': tables, 'relationships': relationships,
            'facts': facts, 'dimensions': dims, 'metrics': metrics, 'skipped': skipped}


def _calc_metrics(ir, columns, root_alias, names, metrics):
    """Self-contained Tableau calculations over one table's columns become metrics (appended)."""
    skipped = []
    for cap, calc in sorted((ir.get('calcs') or {}).items(), key=lambda kv: ('(copy)' in kv[0], kv[0])):
        if not isinstance(calc, dict) or not calc.get('agg_ready'):
            continue
        sql = ' '.join((calc.get('sql') or '').split())
        if not sql or _UNSAFE.search(sql):
            skipped.append({'calculation': cap, 'reason': 'uses parameters, table sub-queries or window logic'})
            continue
        tokens = set(re.findall(r'\b[A-Z_][A-Z0-9_]*\b', sql)) - _SQL_WORDS
        if not tokens or not tokens <= set(columns):
            skipped.append({'calculation': cap, 'reason': 'references fields outside the fact table'})
            continue
        expr = re.sub(r'\b[A-Z_][A-Z0-9_]*\b', lambda m: columns.get(m.group(0), m.group(0)), sql)
        clean = re.sub(r'\s*\(copy\)_\d+$', '', cap).strip()
        name = re.sub(r'[^A-Z0-9]+', '_', clean.upper()).strip('_')[:60] or 'CALC'
        if name in names or any(m['expr'] == expr for m in metrics):
            continue
        names.add(name)
        metrics.append({'table': root_alias, 'name': name, 'expr': expr, 'caption': clean,
                        'source': 'tableau calculation'})
    return skipped


_SQL_WORDS = {'SUM', 'AVG', 'MIN', 'MAX', 'COUNT', 'DISTINCT', 'CASE', 'WHEN', 'THEN', 'ELSE', 'END', 'AND', 'OR',
              'NOT', 'NULL', 'IS', 'IN', 'AS', 'NULLIF', 'COALESCE', 'IFF', 'ROUND', 'ABS', 'DATEDIFF', 'DATEADD',
              'DATE_TRUNC', 'TRUE', 'FALSE', 'LIKE', 'BETWEEN', 'CAST', 'FLOAT', 'NUMBER', 'DATE', 'YEAR', 'MONTH',
              'DAY', 'DIV0', 'ZEROIFNULL', 'LOWER', 'UPPER', 'TRIM'}


def _synonyms(sem):
    """Synonym clause per entry, unique across the whole view: Snowflake rejects a synonym that repeats another
    synonym or an alias/name (e.g. table alias sales_target_v3 and synonym 'SALES_TARGET_V3'). Case is ignored."""
    taken = {str(t['alias']).upper() for t in sem['tables']}
    taken |= {str(e['name']).upper() for e in sem['facts'] + sem['dimensions'] + sem['metrics']}

    def clause(names):
        keep = []
        for n in names:
            key = str(n or '').strip().upper()
            if key and key not in taken:
                taken.add(key)
                keep.append(n)
        return f" WITH SYNONYMS = ({', '.join(_lit(n) for n in keep)})" if keep else ''
    return clause


def _names(entry):
    out = []
    for n in [entry['caption']] + list(entry.get('synonyms') or []):
        if n and n.lower() not in [x.lower() for x in out]:
            out.append(n)
    return out


def ddl(sem):
    def comment(text):
        return ' COMMENT = ' + _lit(text)
    syn = _synonyms(sem)
    lines = ['CREATE OR REPLACE SEMANTIC VIEW ' + sem['name'], '  TABLES (']
    lines.append(',\n'.join(
        f"    {t['alias']} AS {t['table']}" + (f" PRIMARY KEY ({', '.join(_ident(c) for c in key_cols(t['primary_key']))})" if t['primary_key'] else '') +
        syn([t['caption']]) + comment(f"Tableau logical table {t['caption']} ({t['role']})")
        for t in sem['tables']))
    lines.append('  )')
    if sem['relationships']:
        lines.append('  RELATIONSHIPS (')
        lines.append(',\n'.join(f"    {r['name']} AS {r['from']} ({', '.join(_ident(c) for c in key_cols(r['from_key']))}) REFERENCES {r['to']}"
                                for r in sem['relationships']))
        lines.append('  )')
    for block, items in (('FACTS', sem['facts']), ('DIMENSIONS', sem['dimensions'])):
        if items:
            lines.append(f'  {block} (')
            lines.append(',\n'.join(f"    {e['table']}.{e['name']} AS {_ident(e['column'])}"
                                    + syn(_names(e)) + comment(e.get('comment') or ('Tableau field ' + e['caption']))
                                    for e in items))
            lines.append('  )')
    if sem['metrics']:
        lines.append('  METRICS (')
        lines.append(',\n'.join(f"    {m['table']}.{m['name']} AS {m['expr']}"
                                + syn(_names(m)) + comment(m.get('comment') or (m['source'] + ': ' + m['caption']))
                                for m in sem['metrics']))
        lines.append('  )')
    lines.append('  COMMENT = ' + _lit('Generated by the Tableau to SiS accelerator (V3) from the verified Tableau '
                                       + (sem.get('origin') or 'relationship model') + (': ' + sem['caption'] if sem.get('caption') else '')))
    if sem.get('verified_queries'):                  # CF02: sheets proven equal to Tableau (code-written SQL)
        import v3_verified_queries as VQ
        lines.append(VQ.clause(sem['verified_queries']))
    return '\n'.join(lines)


MODES = ('combined', 'per_table')


def relation_sql(sem, plan, mode='combined'):
    """Row-level relation with the dashboard model's column names, read through the Semantic View.

    combined:  one SEMANTIC_VIEW(... DIMENSIONS <all columns of all logical tables>) query.
    per_table: each logical table read through SEMANTIC_VIEW(... DIMENSIONS <its columns>) and
               joined on the view's own declared relationships (fact LEFT JOIN dimension).
    Either way verify() must prove the result equal to the authored relationship model."""
    outputs = ', '.join(f['output'] for f in plan['fields'].values())
    if mode == 'combined':
        dims = ', '.join(f"{e['table']}.{e['name']}" for e in sem['dimensions'] + sem['facts'])
        return f"SELECT {outputs} FROM SEMANTIC_VIEW({sem['name']} DIMENSIONS {dims})"
    if mode != 'per_table':
        raise ValueError('Unknown Semantic View relation mode')
    entries = sem['dimensions'] + sem['facts']

    def part(alias):
        cols = [e for e in entries if e['table'] == alias]
        return (f"(SELECT * FROM SEMANTIC_VIEW({sem['name']} DIMENSIONS "
                + ', '.join(f"{alias}.{e['name']}" for e in cols) + '))')

    def out(alias, column):
        e = next(e for e in entries if e['table'] == alias and e['column'] == column)
        return e['name']
    fact = next(t['alias'] for t in sem['tables'] if t['role'] == 'fact')
    sql = f"SELECT {outputs} FROM {part(fact)} {fact}"
    for r in sem['relationships']:
        on = ' AND '.join(f"{r['from']}.{out(r['from'], a)} = {r['to']}.{out(r['to'], b)}"
                          for a, b in zip(key_cols(r['from_key']), key_cols(r['to_key'])))
        sql += f" LEFT JOIN {part(r['to'])} {r['to']} ON {on}"
    return sql


def _profile(session, sql, plan):
    numeric = [f['output'] for f in plan['fields'].values() if f['datatype'] in NUMERIC]
    keys = sorted({f['output'] for f in plan['fields'].values()
                   if f['remote'] in {k['left'] for k in plan['keys']} and f['owner'] == plan['root']})
    parts = ['COUNT(*) AS ROWS_'] + [f'SUM({c}) AS S_{c}' for c in numeric] + [f'COUNT(DISTINCT {c}) AS D_{c}' for c in keys]
    row = session.sql(f"SELECT {', '.join(parts)} FROM ({sql})").collect()[0]
    return row.as_dict() if hasattr(row, 'as_dict') else dict(row)


def verify(session, sem, plan, mode='combined'):
    """Same rows and same totals as the authored relationship model, or not attached."""
    base = _profile(session, compile_query(plan), plan)
    through = _profile(session, relation_sql(sem, plan, mode), plan)
    checks, ok = [], True
    for k, v in base.items():
        w = through.get(k)
        same = (v == w) if not isinstance(v, (int, float)) or v is None or w is None else \
            abs(float(v) - float(w)) <= 1e-6 * max(1.0, abs(float(v)))
        ok &= bool(same)
        checks.append({'Check': 'Row count' if k == 'ROWS_' else ('Total ' if k.startswith('S_') else 'Distinct ') + k[2:],
                       'Relationship model': v, 'Semantic View': w, 'Equal': bool(same)})
    return ok, checks


def verify_any(session, sem, plan, attempts):
    """Try each relation mode; the first one proven equal is used."""
    last = (False, [], None)
    for mode in MODES:
        try:
            ok, checks = verify(session, sem, plan, mode)
        except Exception as exc:
            attempts.append({'Attempt': f'read through view ({mode})',
                             'Result': type(exc).__name__ + ': ' + str(exc)[:200]})
            continue
        attempts.append({'Attempt': f'read through view ({mode})', 'Result': 'equal' if ok else 'not equal'})
        if ok:
            return True, checks, mode
        last = (False, checks, mode)
    return last


def metric_check(session, sem):
    """Every metric executes on the view (a metric that fails is reported, not hidden)."""
    out = []
    for m in sem['metrics']:
        try:
            row = session.sql(f"SELECT * FROM SEMANTIC_VIEW({sem['name']} METRICS {m['table']}.{m['name']})").collect()[0]
            out.append({'Metric': m['name'], 'Value': list(row.as_dict().values())[0] if hasattr(row, 'as_dict') else row[0],
                        'Source': m['source'], 'Status': 'OK'})
        except Exception as exc:
            out.append({'Metric': m['name'], 'Value': None, 'Source': m['source'], 'Status': type(exc).__name__})
    return out


def _define(session, sem):
    """CREATE the view; a metric Snowflake rejects drops to the next rung, never blocks the view."""
    statement, attempts = None, []
    # Fallback ladder: a Tableau calculation metric Snowflake rejects must not block the view.
    for label, keep in (('all metrics', lambda m: True),
                        ('generated metrics only', lambda m: m['source'] == 'generated'),
                        ('no metrics', lambda m: False)):
        trial = dict(sem, metrics=[m for m in sem['metrics'] if keep(m)])
        try:
            session.sql(ddl(trial)).collect()
        except Exception as exc:
            attempts.append({'Attempt': label, 'Result': type(exc).__name__ + ': ' + str(exc)[:200]})
            continue
        attempts.append({'Attempt': label, 'Result': 'created'})
        dropped = [m['name'] for m in sem['metrics'] if not keep(m)]
        sem = trial
        sem['skipped'] = sem['skipped'] + [{'calculation': n, 'reason': 'rejected by Snowflake in the view definition'}
                                           for n in dropped]
        statement = ddl(sem)
        break
    if statement is None:
        raise RuntimeError('Snowflake rejected the Semantic View definition: ' + attempts[-1]['Result'])
    return sem, statement, attempts


def create(session, plan, ir=None, caption=None, enrich=None):
    """Create the view, prove it equals the relationship model, return the evidence record."""
    sem = model(plan, ir, caption)
    if enrich:
        try:
            enrich(sem)
        except Exception:
            pass                       # descriptions are optional; the model is unchanged
    sem, statement, attempts = _define(session, sem)
    ok, checks, mode = verify_any(session, sem, plan, attempts)
    return {'name': sem['name'], 'ddl': statement, 'verified': ok, 'checks': checks, 'mode': mode,
            'metrics': metric_check(session, sem) if ok else [], 'skipped': sem['skipped'],
            'model': sem, 'attempts': attempts}


def attach(plan, sem_record):
    """A copy of the binding plan whose dashboard queries read through the verified Semantic View."""
    if not sem_record.get('verified'):
        raise ValueError('Semantic View was not verified equal to the relationship model')
    out = dict(plan)
    out['semantic_view'] = sem_record['name']
    out['semantic_mode'] = sem_record.get('mode') or 'combined'
    out['semantic_label'] = label((sem_record.get('model') or {}).get('caption'))
    return out


def bound_relation(plan):
    """The relation for a plan carrying an attached view; recomputed from the plan, never read from payload SQL."""
    if plan.get('semantic_mode') == 'shared':
        # Release 20a: shared view named from the plan's own tables and keys (v3_sv_shared).
        import v3_sv_shared
        return v3_sv_shared.bound_relation(plan)
    name = plan.get('semantic_view')
    base = base_plan(plan)
    lbl = plan.get('semantic_label')
    if lbl is not None and lbl != label(lbl):
        raise ValueError('Invalid Semantic View label')
    expected = view_name(dict(base, semantic_label=lbl) if lbl else base)
    # The lab also allows the Cortex-designed view of the SAME plan (same tables and dimension names,
    # proven equal before it can be attached).
    if name not in (expected, expected + '_CORTEX'):
        raise ValueError('Semantic View name does not match the relationship plan')
    mode = plan.get('semantic_mode') or 'combined'
    if mode not in MODES:
        raise ValueError('Unknown Semantic View relation mode')
    sem = model(base)
    sem['name'] = name
    return relation_sql(sem, base, mode)


