ENRICH_SCHEMA = {'type': 'object', 'properties': {'items': {'type': 'array', 'items': {
    'type': 'object', 'properties': {'name': {'type': 'string'}, 'description': {'type': 'string'},
                                     'synonyms': {'type': 'array', 'items': {'type': 'string'}}},
    'required': ['name', 'description', 'synonyms'], 'additionalProperties': False}}},
    'required': ['items'], 'additionalProperties': False}


def cortex_enricher(session, run):
    """Cortex writes business descriptions and synonyms for existing names only.

    Joins, keys, expressions and names are never taken from the model's answer."""
    import v3_ai

    def enrich(sem):
        entries = sem['dimensions'] + sem['facts'] + sem['metrics']
        evidence = {'tables': [{'name': t['alias'], 'caption': t['caption'], 'role': t['role']} for t in sem['tables']],
                    'fields': [{'name': e['name'], 'table': e['table'], 'caption': e['caption'],
                                'expression': e.get('expr')} for e in entries]}
        out = v3_ai.call(session, run, 'Data model', 'Semantic View descriptions and synonyms',
                         v3_ai._wrap('For each field, write a one-sentence business description (under 25 words) '
                                     'and up to 3 business synonyms an analyst might use. Use the given names '
                                     'exactly; do not invent fields.', evidence), ENRICH_SCHEMA, max_tokens=4000)
        by_name = {e['name']: e for e in entries}
        for item in out.get('items') or []:
            e = by_name.get(item.get('name'))
            if not e:
                continue
            desc = re.sub(r'\s+', ' ', str(item.get('description') or ''))[:300].strip()
            if desc:
                e['comment'] = desc + ' (description by Cortex)'
            syn = [re.sub(r'\s+', ' ', str(s))[:60].strip() for s in item.get('synonyms') or [] if str(s).strip()]
            e['synonyms'] = syn[:3]
    return enrich


def _parse_analyst(data):
    def as_json(v):
        if isinstance(v, str):
            try:
                return json.loads(v)
            except ValueError:
                return v
        return v
    sql, text = None, []
    data = as_json(data)
    msg = as_json(data.get('message', data)) if isinstance(data, dict) else None
    content = as_json(msg.get('content', [])) if isinstance(msg, dict) else []
    for item in content if isinstance(content, list) else []:
        item = as_json(item)
        if isinstance(item, dict) and item.get('type') == 'sql':
            sql = item.get('statement') or item.get('sql')
        elif isinstance(item, dict) and item.get('type') == 'text':
            text.append(item.get('text', ''))
    return sql, '\n\n'.join(t for t in text if t)


def ask_analyst(semantic_view, question):
    """Cortex Analyst (Snowflake REST, called from inside Streamlit in Snowflake)."""
    import _snowflake
    body = {'messages': [{'role': 'user', 'content': [{'type': 'text', 'text': question[:1000]}]}],
            'semantic_view': semantic_view}
    response = _snowflake.send_snow_api_request('POST', '/api/v2/cortex/analyst/message', {}, {}, body, None, 30000)
    status = response.get('status') if isinstance(response, dict) else None
    raw = response.get('content') if isinstance(response, dict) else response
    if status is not None and status >= 400:
        raise RuntimeError(f'Cortex Analyst returned HTTP {status}: {str(raw)[:300]}')
    sql, text = _parse_analyst(raw)
    if sql is None and not text:
        raise RuntimeError('Cortex Analyst returned no answer')
    return sql, text


