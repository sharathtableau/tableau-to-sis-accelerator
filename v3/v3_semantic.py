_WRITE = re.compile(r'\b(INSERT|UPDATE|DELETE|MERGE|CREATE|ALTER|DROP|TRUNCATE|GRANT|REVOKE|CALL|PUT|COPY|USE)\b', re.I)


# E12: SYSTEM$ functions act on the account (cancel queries, wait, change state) and EXECUTE runs other code
_SIDE_EFFECTS = re.compile(r'\bSYSTEM\$|\bEXECUTE\b', re.I)


def run_read_only(session, sql, limit=500):
    """Run Analyst SQL only on explicit request, only a single read-only statement."""
    body = (sql or '').strip().rstrip(';')
    if not _READ_ONLY.match(body) or _WRITE.search(body) or _SIDE_EFFECTS.search(body) or ';' in body:
        raise ValueError('Only a single read-only SELECT is run from here')
    return [r.as_dict() for r in session.sql(f'SELECT * FROM ({body}) LIMIT {int(limit)}').collect()]


# --------------------------------------------------------------------------- #
# Single-table datasources: a Semantic View over the table the dashboard reads
# --------------------------------------------------------------------------- #
# The dashboard keeps reading its verified table binding unchanged; the view exists so Cortex
# Analyst (Ask the data) and the glossary work on the same data. Created only after the binding
# was verified, proven equal to the table (distinct rows and every TOTAL_ metric), then offered.
SINGLE_VERSION = 'single-table-semantic/1'
SINGLE_MODE = 'single_table'
_OBJECT = re.compile(r'[A-Za-z_][A-Za-z_0-9$]*\.[A-Za-z_][A-Za-z_0-9$]*\.[A-Za-z_][A-Za-z_0-9$]*\Z')
_KINDS = (('integer', r'(NUMBER|DECIMAL|NUMERIC)\(\d+,\s*0\)|INT|INTEGER|BIGINT|SMALLINT|TINYINT|BYTEINT'),
          ('real', r'NUMBER|DECIMAL|NUMERIC|FLOAT\d?|DOUBLE( PRECISION)?|REAL'),
          ('datetime', r'TIMESTAMP\w*|DATETIME'),
          ('date', r'DATE'),
          ('boolean', r'BOOLEAN'),
          ('string', r'VARCHAR|CHAR(ACTER)?|STRING|TEXT|TIME'))
_ID_LIKE = re.compile(r'(^|_)(ID|KEY|CODE|ZIP|POSTAL|POSTCODE|NUMBER|NO)(_|$)|LATITUDE|LONGITUDE|_RATE$|(^|_)(YEAR|MONTH|WEEK|DAY)(_|$)')
MAX_COLUMNS = 500


def _kind(sf_type):
    t = str(sf_type or '').upper().strip()
    for kind, pattern in _KINDS:
        if re.match(r'(%s)(?![A-Z0-9_])' % pattern, t):
            return kind
    return None                      # VARIANT, OBJECT, ARRAY, GEOGRAPHY, BINARY, VECTOR: not modelled


def single_spec(session, table):
    """Columns of the bound table, read from Snowflake (DESCRIBE), as a compact typed spec."""
    if not isinstance(table, str) or not _OBJECT.fullmatch(table):
        raise ValueError('A DATABASE.SCHEMA.OBJECT binding is required')
    try:
        described = session.sql('DESCRIBE TABLE ' + table).collect()
    except Exception:
        described = session.sql('DESCRIBE VIEW ' + table).collect()
    columns = []
    for r in described:
        d = {str(k).lower(): v for k, v in (r.as_dict() if hasattr(r, 'as_dict') else dict(r)).items()}
        if str(d.get('kind') or 'COLUMN').upper() != 'COLUMN':
            continue
        kind = _kind(d.get('type'))
        if kind and d.get('name'):
            columns.append({'column': str(d['name']), 'datatype': kind})
    if not columns:
        raise ValueError('The table has no columns that a Semantic View can model')
    if len(columns) > MAX_COLUMNS:
        raise ValueError(f'More than {MAX_COLUMNS} columns')
    return {'version': SINGLE_VERSION, 'table': table, 'columns': columns}


def _single_core(spec):
    if not isinstance(spec, dict) or spec.get('version') != SINGLE_VERSION:
        raise ValueError('Invalid single-table semantic spec')
    if not isinstance(spec.get('table'), str) or not _OBJECT.fullmatch(spec['table']):
        raise ValueError('Invalid single-table semantic source')
    cols = spec.get('columns')
    if not isinstance(cols, list) or not 0 < len(cols) <= MAX_COLUMNS:
        raise ValueError('Invalid single-table semantic columns')
    kinds = {k for k, _ in _KINDS}
    for c in cols:
        if not isinstance(c, dict) or set(c) != {'column', 'datatype'} or c['datatype'] not in kinds:
            raise ValueError('Invalid single-table semantic column')
        quote(c['column'])
    return {'version': SINGLE_VERSION, 'table': spec['table'], 'columns': cols}


def single_name(spec):
    core = _single_core(spec)
    digest = hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest()[:8].upper()
    slug = spec.get('semantic_label')
    if slug is not None and slug != label(slug):
        raise ValueError('Invalid Semantic View label')
    return f'{DB}.{SCHEMA}.{slug}_SV{LAB}_{digest}' if slug else f'{DB}.{SCHEMA}.V3_SV{LAB}_{digest}'


def _dim_name(column, used):
    name = column if _BARE.fullmatch(column) else (re.sub(r'[^A-Z0-9]+', '_', column.upper()).strip('_') or 'COL')
    if name[0].isdigit():
        name = 'C_' + name
    base, n = name, 2
    while name in used:
        name, n = f'{base}_{n}', n + 1
    used.add(name)
    return name


def single_model(spec, ir=None, caption=None):
    """Semantic model of one table: every column a dimension, TOTAL_ / DISTINCT_ metrics, safe calcs."""
    core = _single_core(spec)
    alias = _alias(caption or core['table'].split('.')[-1], set())
    used, dims = set(), []
    for c in core['columns']:
        dims.append({'table': alias, 'name': _dim_name(c['column'], used), 'column': c['column'],
                     'caption': re.sub(r'[_\s]+', ' ', c['column']).strip().title(), 'datatype': c['datatype'],
                     'numeric': c['datatype'] in NUMERIC})
    metrics, names = [], set(used)
    for d in dims:
        if d['numeric'] and not _ID_LIKE.search(d['name']) and 'TOTAL_' + d['name'] not in names:
            names.add('TOTAL_' + d['name'])
            metrics.append({'table': alias, 'name': 'TOTAL_' + d['name'], 'expr': f"SUM({alias}.{d['name']})",
                            'caption': 'Total ' + d['caption'], 'source': 'generated'})
    for d in dims:
        if re.search(r'(^|_)(ID|KEY)(_|$)', d['name']) and d['datatype'] in ('integer', 'string') \
                and 'DISTINCT_' + d['name'] not in names and sum(m['name'].startswith('DISTINCT_') for m in metrics) < 10:
            names.add('DISTINCT_' + d['name'])
            metrics.append({'table': alias, 'name': 'DISTINCT_' + d['name'], 'expr': f"COUNT(DISTINCT {alias}.{d['name']})",
                            'caption': 'Distinct ' + d['caption'].lower(), 'source': 'generated'})
    skipped = []
    if ir is not None:
        columns = {d['column']: f"{alias}.{d['name']}" for d in dims if _BARE.fullmatch(d['column'])}
        skipped = _calc_metrics(ir, columns, alias, names, metrics)
    lbl = spec.get('semantic_label') or label(caption)
    name = single_name(dict(core, semantic_label=lbl) if lbl else core)
    return {'name': name, 'caption': caption, 'origin': 'data source table ' + core['table'],
            'tables': [{'alias': alias, 'table': core['table'], 'caption': caption or core['table'].split('.')[-1],
                        'role': 'fact', 'primary_key': None}],
            'relationships': [], 'facts': [], 'dimensions': dims, 'metrics': metrics, 'skipped': skipped}


def _one_row(session, sql):
    row = session.sql(sql).collect()[0]
    return row.as_dict() if hasattr(row, 'as_dict') else dict(row)


def verify_single(session, sem):
    """Same distinct rows, and every TOTAL_ metric equal to SUM over the table itself."""
    t = sem['tables'][0]
    dims = sem['dimensions']
    src = ', '.join(_ident(d['column']) for d in dims)
    base = {'ROWS_': _one_row(session, f"SELECT COUNT(*) AS N FROM (SELECT DISTINCT {src} FROM {t['table']})")['N']}
    through = {'ROWS_': _one_row(session, 'SELECT COUNT(*) AS N FROM (SELECT DISTINCT * FROM SEMANTIC_VIEW('
                                 + sem['name'] + ' DIMENSIONS ' + ', '.join(f"{d['table']}.{d['name']}" for d in dims)
                                 + '))')['N']}
    totals = [m for m in sem['metrics'] if m['name'].startswith('TOTAL_')]
    if totals:
        by_name = {d['name']: d for d in dims}
        b = _one_row(session, 'SELECT ' + ', '.join(f"SUM({_ident(by_name[m['name'][6:]]['column'])}) AS {m['name']}"
                                                    for m in totals) + ' FROM ' + t['table'])
        v = _one_row(session, 'SELECT * FROM SEMANTIC_VIEW(' + sem['name'] + ' METRICS '
                     + ', '.join(f"{m['table']}.{m['name']}" for m in totals) + ')')
        ordered = list(v.values())
        v = {str(k).upper().strip('"').split('.')[-1]: val for k, val in v.items()}
        for i, m in enumerate(totals):
            base['S_' + m['name'][6:]] = b.get(m['name'])
            # Metric columns come back in the order requested; use it if Snowflake labels them differently.
            through['S_' + m['name'][6:]] = v[m['name']] if m['name'] in v else (
                ordered[i] if len(ordered) == len(totals) else None)
    checks, ok = [], True
    for k, x in base.items():
        y = through.get(k)
        same = (x == y) if not isinstance(x, (int, float)) or x is None or y is None else \
            abs(float(x) - float(y)) <= 1e-6 * max(1.0, abs(float(x)))
        ok &= bool(same)
        checks.append({'Check': 'Distinct rows' if k == 'ROWS_' else 'Total ' + k[2:],
                       'Table': x, 'Semantic View': y, 'Equal': bool(same)})
    return ok, checks


def create_single(session, spec, ir=None, caption=None, enrich=None):
    """Create the view over one bound table, prove it equal to the table, return the evidence record."""
    sem = single_model(spec, ir, caption)
    if enrich:
        try:
            enrich(sem)
        except Exception:
            pass
    sem, statement, attempts = _define(session, sem)
    try:
        ok, checks = verify_single(session, sem)
        attempts.append({'Attempt': 'read through view', 'Result': 'equal' if ok else 'not equal'})
    except Exception as exc:
        ok, checks = False, []
        attempts.append({'Attempt': 'read through view', 'Result': type(exc).__name__ + ': ' + str(exc)[:200]})
    entry = dict(_single_core(spec), semantic_view=sem['name'], semantic_label=label(caption))
    if entry['semantic_label'] is None:
        entry.pop('semantic_label')
    return {'name': sem['name'], 'ddl': statement, 'verified': ok, 'checks': checks, 'mode': SINGLE_MODE,
            'metrics': metric_check(session, sem) if ok else [], 'skipped': sem['skipped'],
            'model': sem, 'attempts': attempts, 'ask': entry if ok else None}


def check_single(entry, binding):
    """An Ask-the-data entry is valid only for the exact table the dashboard is bound to."""
    if not isinstance(entry, dict) or set(entry) - {'version', 'table', 'columns', 'semantic_view', 'semantic_label'}:
        raise ValueError('Invalid Ask-the-data entry')
    if entry.get('table') != binding:
        raise ValueError('Ask-the-data view is not over the bound table')
    if entry.get('semantic_view') != single_name(entry):
        import v3_sv_shared                      # release 20a: one shared view per table
        if not v3_sv_shared.single_allowed(entry):
            raise ValueError('Semantic View name does not match the table spec')
    return entry
