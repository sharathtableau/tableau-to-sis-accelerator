"""Read-only, identity-checked binding of a single authored Snowflake table."""
import re

FQN = re.compile(r'[A-Za-z_][A-Za-z_0-9]*\.[A-Za-z_][A-Za-z_0-9]*\.[A-Za-z_][A-Za-z_0-9]*\Z')


def rows(session, sql):
    return [{str(k).upper(): v for k, v in (r.as_dict() if hasattr(r, 'as_dict') else dict(r)).items()}
            for r in session.sql(sql).collect()]


def compatible(want, actual):
    actual = actual.upper()
    if want == 'string': return actual.startswith(('VARCHAR', 'CHAR', 'TEXT', 'STRING'))
    if want == 'boolean': return actual.startswith('BOOLEAN')
    if want == 'date': return actual == 'DATE'
    if want == 'datetime': return actual.startswith('TIMESTAMP')
    if want == 'real': return actual.startswith(('NUMBER', 'DECIMAL', 'NUMERIC', 'FLOAT', 'DOUBLE', 'REAL', 'INT'))
    if want == 'integer': return actual.startswith(('INT', 'BIGINT', 'SMALLINT')) or bool(re.fullmatch(r'(NUMBER|DECIMAL|NUMERIC)\(\d+,\s*0\)', actual))
    return False


def validate_table(session, table, fields):
    """Explicit and inferred bindings both require exact physical columns/types."""
    if not isinstance(table, str) or not FQN.fullmatch(table):
        raise ValueError('Use an unquoted DATABASE.SCHEMA.OBJECT identifier')
    table = table.upper()
    # ':Measure Names' and other ':'-prefixed fields are generated by Tableau, never physical columns.
    required = [f for f in fields if not f.get('is_calculation') and f.get('datatype') != 'table'
                and not str(f.get('internal') or '').startswith(':')]
    if not required:
        raise ValueError('No physical source fields available for schema validation')
    schema = {r['NAME']: r['TYPE'] for r in rows(session, 'DESCRIBE TABLE ' + table)}
    failures = []
    for field in required:
        name = field['physical']
        if name not in schema:
            failures.append('missing physical column ' + name)
        elif not compatible(field.get('datatype'), schema[name]):
            failures.append('incompatible type for ' + name + ': ' + str(field.get('datatype')) + ' / ' + schema[name])
    if failures:
        raise ValueError('; '.join(failures))
    rows(session, 'SELECT * FROM ' + table + ' LIMIT 0')
    return table


def source_candidates(root, ir):
    """Use datasource IDs and relation references, never captions for discovery."""
    result = {}
    nodes = {d.get('name'): d for d in root.findall('./datasources/datasource')}
    for did, scope in ir.get('field_scopes', {}).items():
        item = {'datasource_id': did, 'caption': scope['caption'], 'state': 'UNRESOLVED', 'table': None}
        result[did] = item
        try:
            if scope.get('binding_error'):
                raise ValueError(scope['binding_error'])
            ds = nodes.get(did)
            if ds is None: raise ValueError('Datasource declaration unavailable')
            named = {n.get('name'): n.find('connection') for n in ds.findall('.//named-connection')}
            upstream = {name: c for name, c in named.items() if c is not None and c.get('class') == 'snowflake'}
            if len(upstream) != 1:
                others = sorted({c.get('class') for c in named.values() if c is not None and c.get('class')
                                 and c.get('class') != 'snowflake'})
                live_other = others and not any(c.get('filename') for c in named.values() if c is not None)
                if live_other and not upstream:
                    # EN19: a live source that is not Snowflake is never queried; the reason names the route
                    raise ValueError(f"Live {', '.join(others)} source: replicate it into Snowflake (for example "
                                     'with a Snowflake connector or a data-load job), then bind the replicated '
                                     'table read-only or point the workbook at it')
                raise ValueError('Automatic binding requires exactly one authored Snowflake connection')
            name, conn = next(iter(upstream.items()))
            if ds.find('.//relationships/relationship') is not None:
                from v3_model_binding import build
                item.update(model_candidate=build(ds), server=conn.get('server', ''), has_extract=ds.find('.//extract') is not None)
                continue
            relations = [r for r in ds.findall('.//relation') if r.get('connection') == name]
            if any(r.get('type') in ('join', 'text', 'union') for r in ds.findall('.//relation')):
                # DM3: a physical join or the author's custom SQL becomes a typed, read-only plan, verified before
                # binding exactly like a relationship model (v3_physical_binding)
                from v3_model_binding import build_live
                item.update(model_candidate=build_live(ds), server=conn.get('server', ''),
                            has_extract=ds.find('.//extract') is not None)
                continue
            tables = set()
            for rel in relations:
                if rel.get('type') != 'table': raise ValueError('Unsupported source relation')
                value = rel.get('table', '')
                parts = re.findall(r'\[([^\]]+)\]', value)
                if '.'.join('[' + p + ']' for p in parts) != value:
                    raise ValueError('Source relation identifier cannot be resolved safely')
                if len(parts) == 1: parts = [conn.get('dbname'), conn.get('schema')] + parts
                elif len(parts) == 2: parts = [conn.get('dbname')] + parts
                if len(parts) != 3 or not all(parts): raise ValueError('Incomplete source database/schema/table')
                table = '.'.join(parts)
                if not FQN.fullmatch(table) or table != table.upper():
                    raise ValueError('Quoted or mixed-case source object needs an explicit binding plan')
                tables.add(table)
            if len(tables) != 1: raise ValueError('Automatic binding requires one physical source table')
            import v3_physical_binding as PB
            table_rels = list({r.get('table'): r for r in relations if r.get('type') == 'table'}.values())
            if len(table_rels) == 1 and PB.needs_projection(ds, table_rels[0]):
                # 6.3: a reserved-word / quoted column -> read through a verified one-table projection
                item.update(model_candidate=PB.single_table_plan(ds, table_rels[0], conn, next(iter(tables))),
                            server=conn.get('server', ''), has_extract=ds.find('.//extract') is not None)
                continue
            item.update(candidate=next(iter(tables)), server=conn.get('server', ''),
                        has_extract=ds.find('.//extract') is not None)
        except ValueError as exc:
            item['reason'] = str(exc)
    return result


def account_host(session):
    """The organization-account hostname of the session (the identity an authored source must match)."""
    identity = rows(session, 'SELECT CURRENT_ACCOUNT() AS LOCATOR, CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, '
                             'CURRENT_ORGANIZATION_NAME() AS ORG, CURRENT_REGION() AS REGION')[0]
    return (str(identity['ORG']) + '-' + str(identity['ACCOUNT_NAME'])).lower().replace('_', '-') + \
        '.snowflakecomputing.com'


def resolve_sources(root, ir, session):
    reports = source_candidates(root, ir)
    if session is None: return {}, list(reports.values())
    identity = None
    for did, item in reports.items():
        if not item.get('candidate') and not item.get('model_candidate'): continue
        try:
            if identity is None:
                identity = rows(session, 'SELECT CURRENT_ACCOUNT() AS LOCATOR, CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, CURRENT_ORGANIZATION_NAME() AS ORG, CURRENT_REGION() AS REGION')[0]
            # Organization-account hostname avoids ambiguous locator/region aliases.
            expected = (str(identity['ORG']) + '-' + str(identity['ACCOUNT_NAME'])).lower().replace('_', '-') + '.snowflakecomputing.com'
            server = item['server'].lower().rstrip('.')
            if server != expected:
                raise ValueError('Authored source account is not the verified organization-account hostname; explicit binding required')
            if item.get('model_candidate'):
                from v3_model_binding import validate
                if item['model_candidate'].get('kind') == 'live-union':
                    from v3_physical_binding import complete_union      # members' missing columns, read-only
                    item['model_candidate'] = complete_union(session, item['model_candidate'])
                checks = validate(session, item['model_candidate'], ir)
                kind = item['model_candidate'].get('kind')
                item.update(state='BOUND', table=item['model_candidate'], model_checks=checks,
                            reason=('Read-only physical join verified (row level, as Tableau)' if kind == 'physical-join'
                                    else 'Live union verified as one read-only UNION ALL (members matched by column '
                                         'name, as Tableau)' if kind == 'live-union'
                                    else 'Live table verified, read through a projection (quoted column names)'
                                    if kind == 'projection'
                                    else 'Author custom SQL verified as one read-only SELECT' if kind == 'custom-sql'
                                    else 'Read-only relationship query verified at fact grain') +
                            '; Tableau equivalence unverified')
                continue
            fields = [f for f in ir['fields'].values() if f['datasource_id'] == did]
            table = validate_table(session, item['candidate'], fields)
            item.update(state='BOUND', table=table, reason='Authored account, table access and physical schema verified. ' +
                        ('Using live upstream data; extract snapshot parity is unverified.' if item['has_extract'] else 'Tableau parity is unverified.'))
        except Exception as exc:
            item.update(state='UNRESOLVED', reason=str(exc))
    bound = {i['caption']: i['table'] for i in reports.values() if i['state'] == 'BOUND'}
    return bound, list(reports.values())
