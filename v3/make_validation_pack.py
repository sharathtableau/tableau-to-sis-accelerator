"""Generate the proof-first validation pack FROM A WORKSTATION.

WHY THIS EXISTS
---------------
The pack has one step that cannot run inside Streamlit in Snowflake: the
Streamlit-side screenshot. Capturing it means starting the generated app on a
local port and photographing it with a real browser (Playwright + Chromium).
The SiS sandbox has no browser, cannot install one, and cannot spawn a second
Streamlit server -- so a pack generated by the in-app button reports visual
BLOCKED for every dashboard, correctly but uselessly.

Everything ELSE in the pack already runs anywhere: the Tableau REST pull, the
per-dashboard live query, the row-level three-way comparison. So the fix is
not to weaken the visual leg -- and emphatically NOT to substitute
headless_render's server-side reconstruction and call it a screenshot -- but
to run the whole pack where a browser exists.

That is all this script does: it drives the SAME functions the in-app button
drives, in the same order, from a machine that has a browser.

    parity.build_cortex_dashboard_validation_report(...)   # sections
    deep_validation._render_app_screenshots(...)           # REAL screenshots
    deep_validation._build_validation_pack(...)            # the pack

There is deliberately no second implementation here. If the pack changes, this
script changes with it, because it calls the same code.

WHAT IT NEEDS
-------------
  * The workbook, as a .twb/.twbx or an already-parsed *_ir.json.
  * Its data available LOCALLY (run `python init_workbook.py <book>.twbx`
    once). The generated app is started for real, so it must be able to
    answer its own queries.
  * A Snowflake connection, by `snow` CLI connection name. One per-dashboard
    query runs through Snowpark and has no DuckDB fallback.
  * Optionally a Tableau workbook id, to pull the real Tableau screenshots
    and crosstabs. Without it the Tableau leg is honestly BLOCKED, exactly as
    it is for a file upload. PAT comes from TABLEAU_PAT_NAME /
    TABLEAU_PAT_SECRET -- never a command-line argument, because arguments
    land in shell history and process listings.

EXAMPLES
--------
    # data legs + real screenshots, no Tableau connection
    python make_validation_pack.py Workbooks/Superstore.twbx -c wbr

    # everything, including the real Tableau screenshots and crosstabs
    python make_validation_pack.py superstore_ir.json -c wbr \
        --tableau-workbook-id 0b53cf7f-cce2-4d1f-b74a-5339aa2916a4

Exit codes: 0 pack written, 2 a precondition is missing (stated), 1 failure.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time


def _stem_for(path: str) -> str:
    base = os.path.basename(path)
    for suffix in (".twbx", ".twb", "_ir.json", ".json"):
        if base.lower().endswith(suffix):
            base = base[: -len(suffix)]
            break
    return "".join(c.lower() if c.isalnum() else "_" for c in base).strip("_")


def _load_ir(path: str):
    """The workbook's IR, parsed from a .twb/.twbx or read from a saved one."""
    if path.lower().endswith(".json"):
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    import tableau_parser
    return tableau_parser.build_ir(path)


def _snowflake_session(connection: str):
    from snowflake.snowpark import Session
    return Session.builder.config("connection_name", connection).create()


def _tableau_conn(args):
    """The Tableau REST connection dict the pack expects, or None.

    Returns None -- rather than a half-populated dict -- when no workbook id
    was given, so the pack reports the Tableau leg BLOCKED for a stated reason
    instead of failing mid-pull."""
    if not args.tableau_workbook_id:
        return None
    if not (os.environ.get("TABLEAU_PAT_NAME")
            and os.environ.get("TABLEAU_PAT_SECRET")):
        print("error: --tableau-workbook-id was given but TABLEAU_PAT_NAME / "
              "TABLEAU_PAT_SECRET are not set in the environment.\n"
              "       Set both and re-run; never pass a token as an argument.",
              file=sys.stderr)
        raise SystemExit(2)
    return {"server_url": args.tableau_server,
            "site_content_url": args.tableau_site,
            "workbook_id": args.tableau_workbook_id}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate the proof-first validation pack from a "
                    "workstation, where a real browser can photograph the "
                    "running app.")
    ap.add_argument("workbook", help="path to a .twb/.twbx, or a parsed *_ir.json")
    ap.add_argument("-c", "--connection", default="wbr",
                    help="`snow` CLI connection name (default: wbr)")
    ap.add_argument("--tableau-workbook-id", default=None,
                    help="Tableau REST workbook id; enables the real Tableau "
                         "screenshots and crosstabs")
    ap.add_argument("--tableau-server",
                    default="https://prod-useast-b.online.tableau.com")
    ap.add_argument("--tableau-site", default="b360bi")
    ap.add_argument("--book-name", default=None,
                    help="display name for the report (default: file name)")
    ap.add_argument("--no-screenshots", action="store_true",
                    help="skip the browser capture; the visual leg is then "
                         "BLOCKED with that stated reason, never substituted")
    args = ap.parse_args(argv)

    if not os.path.exists(args.workbook):
        print(f"error: no such workbook: {args.workbook}", file=sys.stderr)
        return 2

    # Fail on the browser precondition FIRST and by name. Discovering it after
    # a multi-minute run -- and after spending a live Snowflake query per
    # dashboard -- is exactly the experience this script exists to avoid.
    if not args.no_screenshots:
        import app_screenshot as APS
        ok, why = APS.available()
        if not ok:
            print("error: cannot take real screenshots here.\n"
                  f"       {why}\n"
                  "       Fix that, or pass --no-screenshots to build the "
                  "data legs only (the visual leg will be BLOCKED with its "
                  "reason, never substituted with a re-render).",
                  file=sys.stderr)
            return 2

    stem = _stem_for(args.workbook)
    book_name = args.book_name or os.path.basename(args.workbook)
    started = time.time()

    print(f"workbook  : {args.workbook}")
    print(f"stem      : {stem}")

    ir = _load_ir(args.workbook)
    dashboards = ir.get("dashboards") or []
    if not dashboards:
        print("error: this workbook has no dashboards to validate.", file=sys.stderr)
        return 2
    print(f"dashboards: {len(dashboards)}")

    conn = _tableau_conn(args)
    print("tableau   : " + ("REST connection configured (real screenshots + "
                            "crosstabs)" if conn else
                            "none -- Tableau leg will be BLOCKED, stated"))

    try:
        session = _snowflake_session(args.connection)
    except Exception as exc:
        print(f"error: could not open Snowflake connection "
              f"'{args.connection}': {type(exc).__name__}: {exc}\n"
              "       The pack runs one live query per dashboard and has no "
              "DuckDB fallback for it.", file=sys.stderr)
        return 2
    print(f"snowflake : connected via `{args.connection}`")

    try:
        import deep_validation as DV
        import parity

        # Datasource routing comes from datasources.json, written by
        # `init_workbook.py <book>.twbx` during onboarding -- the same file the
        # locally generated apps already read. It is NOT re-derived here: a
        # second routing path is exactly how a workbook ends up rendering
        # another workbook's data on a caption collision, which is the bug
        # MVP item 4 exists to prevent.
        import config
        known = sorted(config.DATASOURCES)
        print(f"datasources: {len(known)} configured "
              f"({', '.join(known[:3])}{' …' if len(known) > 3 else ''})")

        # This process opened a Snowpark session ABOVE, i.e. AFTER config was
        # imported -- so config's import-time precedence check saw "local" and
        # latched the built-in SUPERSTORE.* dev mapping, while backend.run_sql
        # decides Snowflake-vs-DuckDB per CALL and is now sending every query
        # to the account. SUPERSTORE does not exist there, so before this line
        # existed all 21 charts died with `Database 'SUPERSTORE' does not
        # exist` and were reported as "sheet drew no Altair chart" -- the
        # capture layer blamed for a routing-layer failure.
        #
        # Re-resolve under the SAME rule the deployed app runs (config's own
        # _apply_routing_file with deploy_wins=True), never a second mapping
        # of our own -- see MVP item 4's routing landmine.
        moved = config.use_snowflake_routing()
        if moved:
            # engine.py binds ORDERS at ITS import too (`from config import
            # ORDERS`), so the module copy must move in lockstep or every
            # filter/parameter value query keeps naming the phantom database
            # even once the sheets are repointed. This is the same one-line
            # idiom pipeline.py already uses after it repoints DATASOURCES --
            # deliberately reused rather than reworking engine's global, which
            # pipeline.py also assigns directly when it deploys a model view.
            import engine
            engine.ORDERS = config.ORDERS
            print(f"routing   : re-resolved {len(moved)} datasource(s) for "
                  f"Snowflake (session opened after config import)")
            for cap, (before, after) in sorted(moved.items())[:3]:
                print(f"            {cap}: {before} -> {after}")
            if len(moved) > 3:
                print(f"            … and {len(moved) - 3} more")

        print("[1/3] per-dashboard live query + formula/interaction checks …")
        res = parity.check_workbook(ir)
        sections, _rollup = parity.build_cortex_dashboard_validation_report(
            ir, session, book_name, res=res, narrate=False)
        resolved = [s["title"] for s in sections if not s.get("skipped")]
        print(f"      {len(resolved)}/{len(sections)} dashboard section(s) resolved")

        # 2. The step that is the entire reason this script exists.
        shots, notes = {}, []
        if args.no_screenshots:
            notes = [{"dashboard": None, "captured": False,
                      "reason": "screenshot capture was skipped with "
                                "--no-screenshots"}]
            print("[2/3] screenshots skipped (--no-screenshots)")
        else:
            print("[2/3] starting the generated app and photographing every "
                  "dashboard (this takes a couple of minutes) …")
            shots, notes = DV._render_app_screenshots(ir, stem)
            failed = [n for n in notes if not n.get("captured")]
            print(f"      captured {len(shots)} dashboard screenshot(s)")
            for note in failed:
                who = note.get("dashboard") or "all dashboards"
                print(f"      NOT captured — {who}: {note.get('reason')}")

        print("[3/3] building the pack …")
        pack = DV._build_validation_pack(
            ir, sections, book_name, stem, conn=conn,
            streamlit_shots={t: p for t, p in shots.items() if t in resolved},
            uploaded_crosstabs=None)
    except Exception as exc:                                    # noqa: BLE001
        import traceback
        traceback.print_exc()
        print(f"error: pack generation failed: {type(exc).__name__}: {exc}",
              file=sys.stderr)
        return 1
    finally:
        try:
            session.close()
        except Exception:                                       # noqa: BLE001
            pass

    if pack is None:
        print("error: no comparable chart evidence in this workbook, so no "
              "pack was written.", file=sys.stderr)
        return 1

    out_dir = pack.get("out_dir")
    print()
    print(f"pack written to : {out_dir}")
    print(f"workbook verdict: {pack.get('status')}")
    print(f"Tableau screenshots : {len(pack.get('tableau_screenshots', []))}")
    print(f"Streamlit screenshots (REAL, not a re-render): "
          f"{len(pack.get('streamlit_screenshots', []))}")
    print(f"Tableau crosstab views : {len(pack.get('tableau_csv_views', []))}")
    if pack.get("dashboard_report"):
        print(f"client report   : {pack['dashboard_report']}")
    print(f"elapsed         : {time.time() - started:.0f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
